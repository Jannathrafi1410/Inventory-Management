"""Hand-defined candidate cells and anchor parameters for the synthetic simulator.

Assumption: prices/costs are in INR-equivalent units (Rs) as in master anchors; stay windows are
representative periods with lead-time distributions tuned by segment. All numbers are simulator
outputs under stated assumptions, not TBO real P&L.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from typing import List


@dataclass(frozen=True)
class CandidateCell:
    """A candidate inventory cell = destination cluster x stay window x source market x rate plan."""

    cell_id: str
    destination_city: str
    region_group: str
    source_market: str
    rate_plan: str
    product_type: str  # hotel | air | transfer
    checkin_start: date
    checkin_end: date
    stay_nights: int
    # economics
    p: float  # sell price
    c_d: float  # dynamic net cost
    c_b: float  # pre-buy net cost
    k: float  # cash prepaid per unit
    r: float  # refund fraction
    a: float  # fallback availability probability (1 - sell_out_rate target)
    g: float  # goodwill penalty per unserved unit
    contract_type: str
    supplier_cap: int | None
    # demand/behavior
    segment: str  # leisure | business | event | mixed
    base_demand_mean: float
    demand_sigma: float  # lognormal sigma
    capacity: int
    lead_time_min: int
    lead_time_max: int


